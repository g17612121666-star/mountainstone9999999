def short_name(name: str) -> str:
    for a, b in [
        ("联合国教科文组织", ""),
        ("世界地质公园", ""),
        ("国家地质公园", ""),
        ("地质公园", ""),
    ]:
        name = name.replace(a, b)
    return name.replace("（", "").replace("）", "").strip() or name


